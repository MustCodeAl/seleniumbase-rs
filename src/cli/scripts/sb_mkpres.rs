//! `sbrs mkpres`: create a test that builds a slide deck.
//!
//! The file is an ordinary Rust integration test, shaped like the one `sbrs mkfile`
//! writes by default (the rstest `sb` fixture). It builds a presentation with the
//! API of [`BaseCase`](crate::BaseCase): `create_presentation` with the `serif`
//! theme and the `slide` transition, three `add_slide` calls, and
//! `begin_presentation`, which shows the deck in the browser.
//!
//! [`PresentationFile::language`] writes the text of the slides in one of the ten
//! languages of Python's `mkpres` (the method names stay English). The text is
//! rendered by [`PresentationFile::render`]; the golden files under
//! `tests/golden/cli/mkpres/` pin it, and the `cfg(doctest)` item at the bottom of
//! this file compiles them against the current API on every
//! `cargo test --features testing`.

