/// The width rustfmt gives `text`: East Asian characters take two columns.
fn width(text: &str) -> usize {
    text.chars()
        .map(|c| if u32::from(c) >= 0x1100 { 2 } else { 1 })
        .sum()
}

/// `text` as a Rust string literal.
pub(crate) fn literal(text: &str) -> String {
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}

/// The method chain `parts` as a statement, written as rustfmt would: on one line when it
/// is no longer than rustfmt's chain width (60), else the first part (the receiver and its
/// first call) on one line and every other part on a line of its own, indented one level.
///
/// So the generated file is already formatted.
pub(crate) fn chain(parts: &[String]) -> String {
    let one_line = parts.concat();
    if width(&one_line) <= 60 || parts.len() < 2 {
        return format!("{one_line};\n");
    }
    let mut lines = vec![parts[0].clone()];
    lines.extend(parts[1..].iter().map(|part| format!("    {part}")));
    format!("{};\n", lines.join("\n"))
}

/// Every line of `block` indented `depth` levels (blank lines stay blank).
pub(crate) fn indented(block: &str, depth: usize) -> String {
    let pad = "    ".repeat(depth);
    block
        .lines()
        .map(|line| {
            if line.is_empty() {
                "\n".to_owned()
            } else {
                format!("{pad}{line}\n")
            }
        })
        .collect()
}

/// The comment and `use` lines the generated tests start with, and the closing of the test
/// whose statements are `steps` (already indented two levels).
pub(crate) fn test_source(
    generated: &str,
    what: &str,
    stem: &str,
    extra_use: &str,
    steps: &str,
) -> String {
    let fn_name = rust_fn_name(stem);
    format!(
        "//! {generated}\n\
         //!\n\
         //! Run it with `cargo test --test {stem}` when this file is in your crate's\n\
         //! `tests/` folder. It needs Chrome and a matching chromedriver (`sbrs doctor`\n\
         //! checks both). {what} opens in the browser (saved as\n\
         //! `saved_presentations/{stem}.html`) and plays until its last slide, or until\n\
         //! you close the window. With `SB_HEADLESS=true` nobody watches, so nothing is\n\
         //! shown or saved.\n\
         //!\n\
         //! Your crate's dev-dependencies are `seleniumbase-rs` (feature `testing`),\n\
         //! `rstest` and `tokio` (features `macros` and `rt`).\n\
         \n\
         use rstest::rstest;\n\
         {extra_use}\
         use seleniumbase_rs::testing::{{sb, Sb}};\n\
         use seleniumbase_rs::Result;\n\
         \n\
         #[rstest]\n\
         #[tokio::test]\n\
         async fn {fn_name}(sb: Sb) -> Result<()> {{\n\
         \x20   sb.run(async |sb| {{\n\
         {steps}\
         \x20       Ok(())\n\
         \x20   }})\n\
         \x20   .await\n\
         }}\n"
    )
}

/// The statements that create the deck: `create_presentation` with a theme and a
/// transition, written as rustfmt would.
pub(crate) fn create_presentation(theme: &str, transition: &str) -> String {
    chain(&[
        "sb.create_presentation()".to_owned(),
        format!(".theme(PresentationTheme::{theme})"),
        format!(".transition(Transition::{transition})"),
        ".await?".to_owned(),
    ])
}

/// A presentation-building test file to generate.
///
/// # Examples
///
/// ```
/// use seleniumbase_rs::cli::scripts::sb_mkpres::PresentationFile;
/// use seleniumbase_rs::utils::translate::Language;
///
/// # fn main() -> Result<(), seleniumbase_rs::cli::scaffold::ScaffoldError> {
/// let source = PresentationFile::new("tests/deck")?
///     .language(Language::Spanish)
///     .render();
/// assert!(source.contains("async fn deck(sb: Sb) -> Result<()>"));
/// assert!(source.contains("Presione la flecha derecha"));
/// assert!(source.contains("sb.create_presentation()"));
/// # Ok(())
/// # }
/// ```
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PresentationFile {
    name: RelativeName,
    language: Language,
}

impl PresentationFile {
    /// A presentation test called `name`; `.rs` is appended when the name has no extension.
    ///
    /// # Errors
    ///
    /// [`ScaffoldError::InvalidName`] when `name` is not a relative name made of
    /// letters, digits, `_`, `-` and `.`, or has an extension other than `.rs`.
    pub fn new(name: &str) -> Result<Self, ScaffoldError> {
        Ok(Self {
            name: RelativeName::new(name)?.with_extension_or_default("rs")?,
            language: Language::English,
        })
    }

    /// Writes the text of the slides, and the first line of the comment, in `language`.
    #[must_use]
    pub fn language(mut self, language: Language) -> Self {
        self.language = language;
        self
    }

    /// The name of the file, such as `deck.rs`.
    #[must_use]
    pub fn name(&self) -> &str {
        self.name.file_name()
    }

    /// The Rust source of the test.
    #[must_use]
    pub fn render(&self) -> String {
        let words = words(self.language);
        let stem = self.name.file_stem();
        let html = format!("{stem}.html");
        let slide = |content: String, image: Option<&str>| {
            let mut parts = vec![
                format!("sb.add_slide({})", literal(&content)),
            ];
            if let Some(image) = image {
                parts.push(format!(".image({})", literal(image)));
            }
            parts.push(".await?".to_owned());
            chain(&parts)
        };
        let mut steps = create_presentation("Serif", "Slide");
        steps.push_str(&slide(
            format!(
                "<h1>{}</h1><hr /><br /><p>{}</p>",
                words.hello, words.press_right_arrow
            ),
            None,
        ));
        steps.push_str(&slide(
            format!("<h2><b>*</b>  {}  <b>*</b></h2>", words.add_text),
            Some(TEXT_IMAGE),
        ));
        steps.push_str(&slide(
            format!("<h2>{}</h2>", words.goodbye),
            Some(LOGO_IMAGE),
        ));
        steps.push_str(&chain(&[
            "sb.begin_presentation()".to_owned(),
            format!(".filename({})", literal(&html)),
            ".await?".to_owned(),
        ]));
        test_source(
            words.generated,
            "The deck",
            stem,
            "use seleniumbase_rs::api::presentation::{PresentationTheme, Transition};\n",
            &indented(&steps, 2),
        )
    }

    /// Writes the file below the scaffold's root and returns its relative path.
    ///
    /// # Errors
    ///
    /// Any [`ScaffoldError`] from [`Scaffold::write_all`]; in particular
    /// [`ScaffoldError::AlreadyExists`] unless the scaffold is replacing files.
    pub fn create(&self, scaffold: &Scaffold) -> Result<PathBuf, ScaffoldError> {
        let mut created = scaffold.write_all(&[(self.name.clone(), self.render())])?;
        Ok(created.remove(0))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const LANGUAGES: [Language; 10] = [
        Language::English,
        Language::Chinese,
        Language::Dutch,
        Language::French,
        Language::Italian,
        Language::Japanese,
        Language::Korean,
        Language::Portuguese,
        Language::Russian,
        Language::Spanish,
    ];

    fn file(name: &str) -> PresentationFile {
        PresentationFile::new(name).unwrap()
    }

    #[test]
    fn the_deck_is_built_with_the_presentation_api_and_the_rstest_fixture() {
        let source = file("deck").render();
        for part in [
            "use rstest::rstest;",
            "use seleniumbase_rs::api::presentation::{PresentationTheme, Transition};",
            "use seleniumbase_rs::testing::{sb, Sb};",
            "async fn deck(sb: Sb) -> Result<()> {",
            "sb.create_presentation()\n            .theme(PresentationTheme::Serif)\n            .transition(Transition::Slide)\n            .await?;",
            "<h1>Hello</h1><hr /><br /><p>Press Right Arrow</p>",
            "<h2><b>*</b>  Add Text  <b>*</b></h2>",
            "<h2>Goodbye</h2>",
            ".image(\"https://seleniumbase.github.io/cdn/gif/chart_pres.gif\")",
            "sb.begin_presentation().filename(\"deck.html\").await?;",
        ] {
            assert!(source.contains(part), "no {part:?} in:\n{source}");
        }
        assert_eq!(source.matches("sb.add_slide(").count(), 3, "{source}");
    }

    #[test]
    fn a_language_changes_the_slide_text_and_the_comment_only() {
        let english = file("deck").render();
        let chinese = file("deck").language(Language::Chinese).render();
        assert!(chinese.contains("<h1>你好</h1>"), "{chinese}");
        assert!(chinese.contains("按向右箭头"), "{chinese}");
        assert!(chinese.starts_with("//! 由 `sbrs mkpres` 生成的演示文稿测试。\n"));
        assert!(!chinese.contains("Hello"), "{chinese}");
        // Names of methods and types stay English.
        assert!(chinese.contains("sb.create_presentation()"), "{chinese}");
        assert!(chinese.contains("PresentationTheme::Serif"), "{chinese}");
        assert_ne!(english, chinese);
    }

    #[test]
    fn every_language_gives_a_file_that_parses_with_three_slides() {
        for language in LANGUAGES {
            let source = file("deck").language(language).render();
            syn::parse_file(&source).unwrap_or_else(|e| panic!("{language:?}: {e}\n{source}"));
            assert_eq!(source.matches("sb.add_slide(").count(), 3, "{language:?}");
        }
    }

    #[test]
    fn names_get_a_rs_extension_and_a_valid_function_name() {
        let named = file("my-deck");
        assert_eq!(named.name(), "my-deck.rs");
        let source = named.render();
        assert!(source.contains("async fn my_deck(sb: Sb)"), "{source}");
        assert!(source.contains("saved_presentations/my-deck.html"), "{source}");
        assert!(source.contains("filename(\"my-deck.html\")"), "{source}");
        assert!(PresentationFile::new("../deck").is_err());
        assert!(PresentationFile::new("deck.py").is_err());
        assert!(PresentationFile::new("a b").is_err());
    }

    #[test]
    fn a_long_file_name_breaks_the_last_chain_the_way_rustfmt_does() {
        let source = file("a_rather_long_presentation_name").render();
        assert!(
            source.contains(
                "        sb.begin_presentation()\n            \
                 .filename(\"a_rather_long_presentation_name.html\")\n            .await?;"
            ),
            "{source}"
        );
        syn::parse_file(&source).unwrap();
    }

    #[test]
    fn create_writes_the_file_and_never_replaces_one() {
        let dir = tempfile::tempdir().unwrap();
        let scaffold = Scaffold::new(dir.path());
        let deck = file("slides/deck");
        let created = deck.create(&scaffold).unwrap();
        assert_eq!(created, std::path::Path::new("slides/deck.rs"));
        assert_eq!(
            std::fs::read_to_string(dir.path().join(&created)).unwrap(),
            deck.render()
        );
        assert!(matches!(
            deck.create(&scaffold),
            Err(ScaffoldError::AlreadyExists(_))
        ));
        assert!(deck.create(&scaffold.replacing(true)).is_ok());
    }
}

