#[test]
fn extract_inject_revert_gives_the_original_byte_for_byte() {
    let crlf = FORM_ORIGINAL.replace('\n', "\r\n");
    let sources = [
        FORM_ORIGINAL,
        crlf.as_str(),
        "//! Docs.\n#![allow(unused)]\n\nuse seleniumbase_rs::BaseCase;\n\n/// Test.\n#[test]\nfn t() {\n    \
         sb.type_text(\n        \"#user\",\n        \"ada\",\n    ).await?; // typed\n    \
         sb.click(\"#a\"); sb.click(\"#a\"); // twice\n    sb.drag_and_drop(\"#from\", \"#to\");   \n}\n\n\
         #[cfg(test)]\nmod more {\n    fn u() {\n        sb.click(\"#a\");\n    }\n}\n",
        "fn t() { sb.click(\"#a\"); }",
        "use a; fn t() { sb.click(\"#a\"); }\n",
        "fn t() {\n    sb.open(\"https://example.com/\");\n    sb.click(r#\"a[href=\"x\"]\"#);\n}\n",
    ];

    for source in sources {
        for comments in [false, true] {
            let objects = extract(source);
            let injected = inject(source, &objects, comments);
            assert!(injected.changed > 0, "{source}");
            assert_ne!(injected.source, source);

            let reverted = revert(&injected.source, &objects, comments);

            assert_eq!(reverted.source, source, "comments: {comments}");
            assert_eq!(reverted.changed, injected.changed);
        }
    }
}

