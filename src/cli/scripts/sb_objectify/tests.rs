/// The names of the parameters of a method, from its signature, without `self`.
fn parameter_names(signature: &str) -> Vec<String> {
    let open = signature.find('(').expect("a parameter list");
    let mut depth = 0_usize;
    let mut parameters = Vec::new();
    let mut current = String::new();
    for c in signature[open + 1..].chars() {
        match c {
            '(' | '<' | '[' => {
                depth += 1;
                current.push(c);
            }
            ')' if depth == 0 => break,
            ')' | '>' | ']' => {
                depth = depth.saturating_sub(1);
                current.push(c);
            }
            ',' if depth == 0 => parameters.push(std::mem::take(&mut current)),
            _ => current.push(c),
        }
    }
    parameters.push(current);
    parameters
        .iter()
        .filter_map(|parameter| parameter.split_once(':'))
        .map(|(name, _)| name.trim().to_owned())
        .collect()
}

/// The signatures of the `BaseCase` methods called `name`.
fn basecase_signatures(name: &str) -> Vec<String> {
    let entries: Vec<serde_json::Value> = serde_json::from_str(API_INDEX).expect("the API index");
    entries
        .iter()
        .filter(|entry| entry["name"] == name && entry["owner"] == "BaseCase")
        .filter_map(|entry| entry["signature"].as_str().map(str::to_owned))
        .collect()
}

#[test]
fn every_selector_method_takes_a_selector_where_the_list_says() {
    let methods = SELECTOR_FIRST
        .iter()
        .map(|name| (*name, 0))
        .chain(SELECTOR_SECOND.iter().map(|name| (*name, 1)))
        .chain(
            TWO_SELECTORS
                .iter()
                .flat_map(|name| [(*name, 0), (*name, 1)]),
        );
    for (name, position) in methods {
        let signatures = basecase_signatures(name);
        assert!(!signatures.is_empty(), "BaseCase has no method `{name}`");
        let names = parameter_names(&signatures[0]);
        let parameter = names.get(position).unwrap_or_else(|| {
            panic!("`{name}` has no parameter {position}: {}", signatures[0]);
        });
        assert!(
            parameter.contains("css") || parameter.contains("selector"),
            "parameter {position} of `{name}` is `{parameter}`, not a selector: {}",
            signatures[0]
        );
    }
}

