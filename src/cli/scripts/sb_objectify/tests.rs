const HEADER: &str =
    "// PAGE OBJECTS FILE >>> (autogenerated by `sbrs extract-objects`)\n#![allow(dead_code)]\n";

fn extract(source: &str) -> String {
    extract_text(source, None).expect("extract").page_objects
}

/// The constants of a module: `(name, selector)`.
type Constants<'a> = &'a [(&'a str, &'a str)];

/// A module of a page objects file: `(url, name, constants)`.
type Module<'a> = (Option<&'a str>, &'a str, Constants<'a>);

/// A page objects file of `modules`, each `(url, name, [(constant, selector)])`; the selector
/// is written as a plain string literal.
fn objects_file(modules: &[Module]) -> String {
    let mut text = HEADER.to_owned();
    for (url, name, constants) in modules {
        text.push('\n');
        if let Some(url) = url {
            text.push_str(&format!("/// {url}\n"));
        }
        text.push_str(&format!("pub mod {name} {{\n"));
        for (constant, selector) in *constants {
            text.push_str(&format!(
                "    pub const {constant}: &str = \"{selector}\";\n"
            ));
        }
        text.push_str("}\n");
    }
    text
}

/// The constant names of a page objects file, in order.
fn constant_names(objects: &str) -> Vec<String> {
    objects
        .lines()
        .filter_map(|line| line.trim().strip_prefix("pub const "))
        .filter_map(|rest| rest.split(':').next())
        .map(str::to_owned)
        .collect()
}

/// The module names of a page objects file, in order.
fn module_names(objects: &str) -> Vec<String> {
    objects
        .lines()
        .filter_map(|line| line.strip_prefix("pub mod "))
        .filter_map(|rest| rest.strip_suffix(" {"))
        .map(str::to_owned)
        .collect()
}

fn inject(source: &str, objects: &str, comments: bool) -> Rewrite {
    inject_text(source, objects, comments).expect("inject")
}

fn revert(source: &str, objects: &str, comments: bool) -> Rewrite {
    revert_text(source, objects, comments).expect("revert")
}

