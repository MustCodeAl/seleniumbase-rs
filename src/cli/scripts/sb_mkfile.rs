//! `sbrs mkfile` (also `sbrs new`): create one browser-test file.
//!
//! The file is an ordinary Rust integration test. Its shape is a [`Syntax`]: by
//! default the rstest `sb` fixture of [`testing`](crate::testing), which gives
//! a test the run configuration, reruns and the evidence of a failure. The
//! other syntaxes are a `BaseCase` made and quit by hand, the
//! [`run_browser_test`](crate::run_browser_test) closure, and two pure CDP
//! forms. [`TestFile::language`] localises the strings and the first comment,
//! and [`TestFile::recorder`] adds a `recorder_breakpoint` for Recorder Mode.
//!
//! The text is rendered by [`TestFile::render`]; the golden files under
//! `tests/golden/cli/mkfile/` pin it, and the `cfg(doctest)` item at the bottom
//! of this file compiles those golden files against the current API on every
//! `cargo test --features testing`.

use std::path::PathBuf;

use url::Url;

use crate::cli::scaffold::{rust_fn_name, RelativeName, Scaffold, ScaffoldError};
use crate::utils::translate::Language;

/// The page the example test opens when no URL is given.
const EXAMPLE_URL: &str = "https://example.com";

/// What the recorder breakpoint tells the person who records.
const RECORDER_MESSAGE: &str = "Click what you want to test, then press c here";

/// The shape of a generated test: Python's syntax formats, as they are in Rust.
///
/// # Examples
///
/// ```
/// use seleniumbase_rs::cli::scripts::sb_mkfile::Syntax;
///
/// assert_eq!(Syntax::default(), Syntax::Fixture);
/// assert!(Syntax::CdpManager.is_cdp());
/// assert_eq!(Syntax::BaseCase.flag(), "--bc");
/// ```
#[derive(Clone, Copy, Debug, Default, Eq, Hash, PartialEq)]
pub enum Syntax {
    /// `#[rstest]` with the `sb` fixture (`--pf`, the default). Needs the
    /// feature `testing`.
    #[default]
    Fixture,
    /// A [`BaseCase`](crate::BaseCase) made and quit by hand (`--bc`).
    BaseCase,
    /// A closure run by [`run_browser_test`](crate::run_browser_test) (`--cm`).
    ContextManager,
    /// `#[rstest]` with the pure CDP `sb_cdp` fixture (`--dc`). Needs the
    /// feature `testing`.
    CdpFixture,
    /// A pure CDP [`Browser`](crate::sb_cdp::Browser) launched and closed by
    /// hand (`--dm`).
    CdpManager,
}

impl Syntax {
    /// Whether the test drives Chrome over pure CDP, with no chromedriver.
    #[must_use]
    pub const fn is_cdp(self) -> bool {
        matches!(self, Self::CdpFixture | Self::CdpManager)
    }

    /// The flag that picks this syntax on the command line.
    #[must_use]
    pub const fn flag(self) -> &'static str {
        match self {
            Self::Fixture => "--pf",
            Self::BaseCase => "--bc",
            Self::ContextManager => "--cm",
            Self::CdpFixture => "--dc",
            Self::CdpManager => "--dm",
        }
    }
}

