//! `sbrs extract-objects`, `inject-objects`, `objectify` and `revert-objects`: the selectors
//! of a Rust test file as page objects.
//!
//! Python's `sbase extract-objects`, `inject-objects`, `objectify` and `revert-objects` move the
//! selectors of a SeleniumBase test into a `page_objects.py` file and back. The commands here do
//! the same for a Rust test, on the text of the file: the source is read with a small tokenizer,
//! so no syntax tree is needed and nothing else in the file is touched.
//!
//! - [`extract_objects`] finds the string literals that are the selector argument of a
//!   [`SELECTOR_FIRST`], [`SELECTOR_SECOND`] or [`TWO_SELECTORS`] method, groups them by the page
//!   that the last `open` or `goto` ([`NAVIGATION_METHODS`]) of the same function loaded, and
//!   writes them as constants of `page_objects.rs` next to the test file.
//!
//!   ```text
//!   // PAGE OBJECTS FILE >>> (autogenerated by `sbrs extract-objects`)
//!   #![allow(dead_code)]
//!
//!   /// https://example.com/login
//!   pub mod example_com_login {
//!       pub const USER: &str = "#user";
//!       pub const BUTTON_GO: &str = "button.go";
//!   }
//!   ```
//!
//! - [`inject_objects`] replaces those literals by `page_objects::<page>::NAME` and declares
//!   `mod page_objects;` above the first item of the file. With `comments`, every changed line
//!   ends with `// "selector"`.
//! - [`objectify`] is both.
//! - [`revert_objects`] puts the literals back, takes the `// "selector"` comments off when it is
//!   asked to, and removes the `mod page_objects;` line when no page object is left in the file.
//!   Extract, inject and revert give the original file back byte for byte.
//!
//! # Names
//!
//! A module is named with the words of the page's URL (`https://example.com/login` gives
//! `example_com_login`; selectors found before any `open` go to `page`). A constant is named with
//! the first six words of the selector in capitals, with `_2`, `_3`, ... when two selectors of a
//! page give the same name, and `CSS_1`, `CSS_2`, ... for a selector with no word in it. Python
//! names every selector `css_N` in a single `Page` class; the words of the selector make the
//! test easier to read.
//!
//! # What is left alone
//!
//! A selector that is not a lone string literal (`sb.click(&selector)`, `sb.click(format!(..))`),
//! a literal that spans lines, and a call that is in a comment or in a string. The receiver of a
//! call is not looked at, so `page.click("#a")` of the pure CDP engine is found too.
//!
//! The lists of the methods are kept here, with the scanner, and a test checks every name
//! against the generated API index (`src/mcp/dev/api_index.json`); `sbrs methods` lists the
//! common methods of the test API in `crates/cli/src/info.rs`.

