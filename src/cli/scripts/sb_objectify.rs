/// Methods that load a page and take its URL as the first argument. The selectors that follow
/// in the same function belong to that page.
pub const NAVIGATION_METHODS: &[&str] = &[
    "goto",
    "open",
    "open_url",
    "uc_open_with_disconnect",
    "uc_open_with_reconnect",
];

/// The positions of the selector arguments of a call to `method`, counted from 0.
///
/// The answer comes from [`SELECTOR_FIRST`] (`[0]`), [`SELECTOR_SECOND`] (`[1]`) and
/// [`TWO_SELECTORS`] (`[0, 1]`); a method in none of them takes no selector, and the answer is empty.
#[must_use]
pub fn selector_positions(method: &str) -> &'static [usize] {
    if SELECTOR_FIRST.contains(&method) {
        &[0]
    } else if SELECTOR_SECOND.contains(&method) {
        &[1]
    } else if TWO_SELECTORS.contains(&method) {
        &[0, 1]
    } else {
        &[]
    }
}

/// Whether a call to `method` loads a page ([`NAVIGATION_METHODS`]): the selectors after it, in
/// the same function, belong to that page.
#[must_use]
pub fn is_navigation_method(method: &str) -> bool {
    NAVIGATION_METHODS.contains(&method)
}

