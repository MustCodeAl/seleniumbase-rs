//! `sbrs mkchart`: create a test that shows a chart on a slide.
//!
//! The file is an ordinary Rust integration test, shaped like the one `sbrs mkfile`
//! writes by default (the rstest `sb` fixture). It builds a pie chart with the API of
//! [`BaseCase`](crate::BaseCase): `create_pie_chart` with six `add_data_point` calls,
//! `extract_chart` to take its HTML, one `add_slide` that carries it, in a
//! presentation with the `sky` theme and the `slide` transition, and
//! `begin_presentation` to show it in the browser.
//!
//! [`ChartFile::language`] writes the label of the data points and the comment in one
//! of the ten languages of Python's `mkchart` (the method names stay English). The text
//! is rendered by [`ChartFile::render`]; the golden files under
//! `tests/golden/cli/mkchart/` pin it, and the `cfg(doctest)` item at the bottom of
//! this file compiles them against the current API on every
//! `cargo test --features testing`.

use std::path::PathBuf;

use super::sb_mkpres::{chain, create_presentation, indented, literal, test_source};
use crate::cli::scaffold::{RelativeName, Scaffold, ScaffoldError};
use crate::utils::translate::Language;

/// The data points of the example chart: the suffix of the label and the value.
const POINTS: [(&str, u32); 6] = [("A", 36), ("B", 33), ("C", 27), ("D", 21), ("E", 18), ("F", 15)];

/// The words a language changes in a generated chart test.
struct Words {
    /// The first line of the file's comment.
    generated: &'static str,
    /// The label of a data point, before its letter.
    item: &'static str,
    /// The start of the comment that lists the kinds of chart.
    select_option: &'static str,
    /// The kinds of chart, in that language: pie, bar, column, line and area.
    chart_options: &'static str,
}

