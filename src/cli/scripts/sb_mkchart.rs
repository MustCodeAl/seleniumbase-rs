/// A chart-presenting test file to generate.
///
/// # Examples
///
/// ```
/// use seleniumbase_rs::cli::scripts::sb_mkchart::ChartFile;
/// use seleniumbase_rs::utils::translate::Language;
///
/// # fn main() -> Result<(), seleniumbase_rs::cli::scaffold::ScaffoldError> {
/// let source = ChartFile::new("tests/chart")?.language(Language::French).render();
/// assert!(source.contains("async fn chart(sb: Sb) -> Result<()>"));
/// assert!(source.contains("sb.create_pie_chart()"));
/// assert!(source.contains("sb.add_data_point(\"Objet A\", 36.0)"));
/// # Ok(())
/// # }
/// ```
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ChartFile {
    name: RelativeName,
    language: Language,
}

impl ChartFile {
    /// A chart test called `name`; `.rs` is appended when the name has no extension.
    ///
    /// # Errors
    ///
    /// [`ScaffoldError::InvalidName`] when `name` is not a relative name made of
    /// letters, digits, `_`, `-` and `.`, or has an extension other than `.rs`.
    pub fn new(name: &str) -> Result<Self, ScaffoldError> {
        Ok(Self {
            name: RelativeName::new(name)?.with_extension_or_default("rs")?,
            language: Language::English,
        })
    }

    /// Writes the labels of the data points, and the first line of the comment, in `language`.
    #[must_use]
    pub fn language(mut self, language: Language) -> Self {
        self.language = language;
        self
    }

    /// The name of the file, such as `chart.rs`.
    #[must_use]
    pub fn name(&self) -> &str {
        self.name.file_name()
    }

    /// The Rust source of the test.
    #[must_use]
    pub fn render(&self) -> String {
        let words = words(self.language);
        let stem = self.name.file_stem();
        let mut steps = create_presentation("Sky", "Slide");
        steps.push('\n');
        steps.push_str(&format!(
            "// {} => {}\n\
             // Call the matching method: create_pie_chart, create_bar_chart,\n\
             // create_column_chart, create_line_chart or create_area_chart.\n",
            words.select_option, words.chart_options
        ));
        steps.push_str(&chain(&[
            "sb.create_pie_chart()".to_owned(),
            ".title(\"Chart 1\")".to_owned(),
            ".await?".to_owned(),
        ]));
        for (letter, value) in POINTS {
            steps.push_str(&chain(&[
                format!(
                    "sb.add_data_point({}, {value}.0)",
                    literal(&format!("{} {letter}", words.item))
                ),
                ".await?".to_owned(),
            ]));
        }
        steps.push_str("let chart = sb.extract_chart().await?;\n");
        steps.push_str(&chain(&[
            "sb.add_slide(&format!(\"<p>Chart Demo</p>{chart}\"))".to_owned(),
            ".await?".to_owned(),
        ]));
        steps.push('\n');
        steps.push_str(&chain(&[
            "sb.begin_presentation()".to_owned(),
            format!(".filename({})", literal(&format!("{stem}.html"))),
            ".await?".to_owned(),
        ]));
        test_source(
            words.generated,
            "The chart slide",
            stem,
            "use seleniumbase_rs::api::presentation::{PresentationTheme, Transition};\n",
            &indented(&steps, 2),
        )
    }

    /// Writes the file below the scaffold's root and returns its relative path.
    ///
    /// # Errors
    ///
    /// Any [`ScaffoldError`] from [`Scaffold::write_all`]; in particular
    /// [`ScaffoldError::AlreadyExists`] unless the scaffold is replacing files.
    pub fn create(&self, scaffold: &Scaffold) -> Result<PathBuf, ScaffoldError> {
        let mut created = scaffold.write_all(&[(self.name.clone(), self.render())])?;
        Ok(created.remove(0))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const LANGUAGES: [Language; 10] = [
        Language::English,
        Language::Chinese,
        Language::Dutch,
        Language::French,
        Language::Italian,
        Language::Japanese,
        Language::Korean,
        Language::Portuguese,
        Language::Russian,
        Language::Spanish,
    ];

    fn file(name: &str) -> ChartFile {
        ChartFile::new(name).unwrap()
    }

    #[test]
    fn the_chart_is_built_with_the_chart_api_inside_a_sky_presentation() {
        let source = file("chart").render();
        for part in [
            "async fn chart(sb: Sb) -> Result<()> {",
            "PresentationTheme::Sky",
            "Transition::Slide",
            "sb.create_pie_chart().title(\"Chart 1\").await?;",
            "sb.add_data_point(\"Item A\", 36.0).await?;",
            "sb.add_data_point(\"Item F\", 15.0).await?;",
            "// Select option => \"pie\", \"bar\", \"column\", \"line\", \"area\"",
            "let chart = sb.extract_chart().await?;",
            "sb.add_slide(&format!(\"<p>Chart Demo</p>{chart}\")).await?;",
            "sb.begin_presentation().filename(\"chart.html\").await?;",
        ] {
            assert!(source.contains(part), "no {part:?} in:\n{source}");
        }
        assert_eq!(source.matches("sb.add_data_point(").count(), 6, "{source}");
    }

    #[test]
    fn a_language_changes_the_labels_and_the_comment_only() {
        let source = file("chart").language(Language::Chinese).render();
        assert!(source.contains("sb.add_data_point(\"目的 A\", 36.0)"), "{source}");
        assert!(source.contains("// 选择选项 => \"饼图\""), "{source}");
        assert!(source.starts_with("//! 由 `sbrs mkchart` 生成的图表演示文稿测试。\n"));
        assert!(source.contains("sb.create_pie_chart()"), "{source}");
        assert!(!source.contains("Item"), "{source}");
    }

    #[test]
    fn every_language_gives_a_file_that_parses_with_six_points() {
        for language in LANGUAGES {
            let source = file("chart").language(language).render();
            syn::parse_file(&source).unwrap_or_else(|e| panic!("{language:?}: {e}\n{source}"));
            assert_eq!(source.matches("sb.add_data_point(").count(), 6, "{language:?}");
        }
    }

    #[test]
    fn names_get_a_rs_extension_and_bad_names_are_refused() {
        let named = file("q3-results");
        assert_eq!(named.name(), "q3-results.rs");
        let source = named.render();
        assert!(source.contains("async fn q3_results(sb: Sb)"), "{source}");
        assert!(source.contains("filename(\"q3-results.html\")"), "{source}");
        assert!(ChartFile::new("../chart").is_err());
        assert!(ChartFile::new("chart.html").is_err());
    }

    #[test]
    fn create_writes_the_file_and_never_replaces_one() {
        let dir = tempfile::tempdir().unwrap();
        let scaffold = Scaffold::new(dir.path());
        let chart = file("charts/q3");
        let created = chart.create(&scaffold).unwrap();
        assert_eq!(created, std::path::Path::new("charts/q3.rs"));
        assert_eq!(
            std::fs::read_to_string(dir.path().join(&created)).unwrap(),
            chart.render()
        );
        assert!(matches!(
            chart.create(&scaffold),
            Err(ScaffoldError::AlreadyExists(_))
        ));
    }
}

